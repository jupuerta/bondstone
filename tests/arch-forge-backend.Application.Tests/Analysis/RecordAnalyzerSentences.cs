    private const string Recording =
        "../../../../../../arch-forge-frontend/src/export/__fixtures__/analyzer-sentences.json";

    private readonly List<(string Scenario, LocalizedText Text)> _collected = [];

    [Fact(Skip = "Generator: writes into the frontend repository. Run by hand when a sentence changes.")]
    public void Record()
    {
        foreach (var (name, builder) in Scenarios())
        {
            var result = ReferenceArchitecture.Analyze(builder.Build());

            foreach (var finding in result.Findings)
            {
                Add(name, finding.Message);
                Add(name, finding.Explanation);
                Add(name, finding.Suggestion);
                Add(name, finding.Fix?.Label);
            }

            foreach (var rule in result.Coverage)
                Add(name, rule.Reason);
        }

        var options = new JsonSerializerOptions(JsonSerializerDefaults.Web) { WriteIndented = true };
        options.Converters.Add(new JsonStringEnumConverter());

        var payload = new
        {
            note = "Generated by RecordAnalyzerSentences in the backend test project - do not edit by hand. "
                   + "One recording per (key, argument names) so check-catalogs.mjs can verify that every "
                   + "template's placeholders are covered by the arguments the backend actually sends.",
            sentences = _collected
                .OrderBy(entry => entry.Text.Key, StringComparer.Ordinal)
                .Select(entry => new { scenario = entry.Scenario, text = entry.Text })
                .ToList()
        };

        File.WriteAllText(Path.GetFullPath(Recording), JsonSerializer.Serialize(payload, options) + "\n");
    }

    private void Add(string scenario, LocalizedText? text)
    {
        if (text is null)
            return;

        if (_collected.Any(entry => Shape(entry.Text) == Shape(text)))
            return;

        _collected.Add((scenario, text));

        foreach (var nested in (text.Args ?? new Dictionary<string, object>()).Values.OfType<LocalizedText>())
            Add(scenario, nested);
    }

    private static string Shape(LocalizedText text) =>
        text.Key + "|" + string.Join(",", (text.Args ?? new Dictionary<string, object>()).Keys.OrderBy(k => k, StringComparer.Ordinal));

